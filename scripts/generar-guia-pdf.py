def titulo(texto, nivel=0):
    """Encabezado con ancla para la tabla de contenido (enlaces clicables)."""
    key = "h_%s" % hashlib.md5(texto.encode()).hexdigest()[:8]
    estilo = H1 if nivel == 0 else H2
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, texto), estilo)
    p.bookmark_name = texto
    p.bookmark_level = nivel
    p.bookmark_text = texto
    p.bookmark_key = key
    return p

def seccion(texto):
    """H1 con prevencion de titulos huerfanos al pie de pagina."""
    return [CondPageBreak(4.2 * cm), titulo(texto, 0),
            HRFlowable(width="100%", thickness=1.1, color=ACCENT, spaceBefore=0, spaceAfter=10)]

def tabla(datos, ratios, con_caption=None):
    """Tabla estandar: celdas envueltas en Paragraph, centrada, ancho 100% util."""
    widths = [r * ANCHO_UTIL for r in ratios]
    filas = [[Paragraph("<b>%s</b>" % c, TH) for c in datos[0]]]
    for fila in datos[1:]:
        filas.append([c if isinstance(c, (Paragraph, Table)) else Paragraph(c, TD) for c in fila])
    t = Table(filas, colWidths=widths, hAlign="CENTER", repeatRows=1)
    estilo = [
        ("BACKGROUND", (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#c9ccd4")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 5.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5.5),
    ]
    for i in range(1, len(filas)):
        if i % 2 == 0:
            estilo.append(("BACKGROUND", (0, i), (-1, i), TABLE_ROW_ODD))
    t.setStyle(TableStyle(estilo))
    bloque = [Spacer(1, 6), t]
    if con_caption:
        bloque += [Paragraph(con_caption, CAPTION)]
    bloque.append(Spacer(1, 8))
    return bloque

def callout(texto, etiqueta):
    c = Table([[Paragraph("<b>%s</b>" % texto, STAT)], [Paragraph(etiqueta, STATL)]],
              colWidths=[ANCHO_UTIL * 0.62], hAlign="CENTER")
    c.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), BG_PAGE),
        ("BOX", (0, 0), (-1, -1), 1.1, ACCENT),
        ("TOPPADDING", (0, 0), (-1, 0), 10),
        ("BOTTOMPADDING", (0, -1), (-1, -1), 10),
        ("TOPPADDING", (0, 1), (-1, 1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return [Spacer(1, 6), c, Spacer(1, 10)]

